"""One explicitly invoked public Bybit BTCUSDT M1 provenance smoke (no trading).

This CI-only script is NOT imported by the offline suite. It calls the existing
unsigned historical GET adapter, validates a completed historical UTC hour,
runs two labeled test-only VIRTUAL orders, and writes a verifiable OHLCV sample
plus SIMULATION financial report as separate GitHub Actions artifacts.

No private market/order/account API, exchange credentials, PAPER, MAIN, H-017,
Scanner, Robot, or runtime service is accessed. Failure to obtain real market
data is a hard error, never replaced by synthetic data or a stale fixture.
"""
from __future__ import annotations

from decimal import Decimal
import json
from pathlib import Path

from research.simulator_v2.cache import _checksum, _rows
from research.simulator_v2.history import (
    MINUTE_MS, HistoryChunk, iter_closed_m1_chunks,
)
from research.simulator_v2.report import run_verified_chunks
from research.simulator_v2.session import VirtualReplaySession
from research.simulator_v2.virtual_exchange import MarketRequest

SYMBOL = "BTCUSDT"
SOURCE_ID = "BYBIT_PUBLIC_V5_M1"
# 2026-10-01 00:00:00 UTC -> 2026-10-01 01:00:00 UTC, 60 CLOSED M1 candles
START_MS = 1_790_812_800_000
END_MS = START_MS + 60 * MINUTE_MS


def collect_public_sample(output_dir: Path) -> dict[str, object]:
    """Fetch a single verified UTC hour and persist evidence only after proof."""
    if not isinstance(output_dir, Path) or output_dir.is_symlink():
        raise ValueError("a dedicated non-symlink output directory is required")
    chunks = tuple(iter_closed_m1_chunks(
        symbol=SYMBOL, start_ms=START_MS, end_ms=END_MS,
        latest_closed_boundary_ms=END_MS, chunk_minutes=60,
        page_limit=100, source_id=SOURCE_ID,
    ))
    if len(chunks) != 1:
        raise ValueError("Bybit M1 sample was not exactly one complete hour")
    item = chunks[0]
    if (
        not isinstance(item, HistoryChunk)
        or item.start_ms != START_MS or item.end_ms != END_MS
        or item.symbol != SYMBOL or item.source_id != SOURCE_ID
        or len(item.candles) != 60 or item.sha256 != _checksum(_rows(item.candles))
    ):
        raise ValueError("invalid or incomplete public BTCUSDT M1 sample")

    # These orders are FIXED ACCOUNTING PROBES; not generated by Scanner/Robot.
    session = VirtualReplaySession(
        simulation_run_id="public_m1_smoke_20261001",
        symbol=SYMBOL, initial_balance=Decimal("1000"),
        taker_fee_rate=Decimal("0.0006"),
    )
    schedule = {
        START_MS + MINUTE_MS: MarketRequest(
            order_id="sample_entry", side="BUY", quantity=Decimal("0.001"),
        ),
        START_MS + 11 * MINUTE_MS: MarketRequest(
            order_id="sample_exit", side="SELL", quantity=Decimal("0.001"),
        ),
    }
    report = run_verified_chunks(session, (item,), order_schedule=schedule)
    if (
        report.minutes != 60 or report.virtual_fills != 2
        or report.final_position_quantity != 0 or report.pending_order_id is not None
    ):
        raise ValueError("SIMULATION accounting probe did not complete")
    sample = {
        "schema": "SIMULATOR_V2_BYBIT_PUBLIC_M1_SAMPLE_V1",
        "source": "unsigned GET https://api.bybit.com/v5/market/kline",
        "category": "linear", "interval": "1",
        "symbol": SYMBOL, "source_id": SOURCE_ID,
        "start_ms": START_MS, "end_ms": END_MS,
        "sha256": item.sha256,
        "candles": _rows(item.candles),
    }
    result = report.to_payload()
    result["sample_schema"] = sample["schema"]
    result["sample_sha256"] = item.sha256
    result["warning"] = (
        "Fixed test-only virtual orders; not Scanner/Robot decisions "
        "or a strategy profitability test"
    )
    output_dir.mkdir(parents=True, exist_ok=False)
    with (output_dir / "public_m1_candles.json").open("x", encoding="utf-8") as file:
        json.dump(sample, file, ensure_ascii=False, sort_keys=True, indent=2)
    with (output_dir / "virtual_account_report.json").open("x", encoding="utf-8") as file:
        json.dump(result, file, ensure_ascii=False, sort_keys=True, indent=2)
    return result


def main() -> None:
    report = collect_public_sample(Path("simulator-v2-public-m1-sample"))
    print(
        "PUBLIC_REAL_M1_SAMPLE_VERIFIED"
        " symbol=BTCUSDT source=BYBIT_PUBLIC_V5_M1"
        f" start_ms={START_MS} end_ms={END_MS}"
        f" minutes={report['minutes']} fills={report['virtual_fills']}"
        f" sha256={report['sample_sha256']}"
        f" virtual_net_pnl={report['total_net_pnl']}"
        " strategy=NONE"
    )


if __name__ == "__main__":
    main()
