def calculate_potential_move(
    pattern,
    geometry
):
    """
    ?????????? ????????????? ??? ????????? ? ?????????.

    ???????:

        start_width / reference_price * 100

    ??? Falling Wedge ??????????? UP.
    ??? Rising Wedge ??????????? DOWN.
    """

    if not isinstance(geometry, dict):
        return None

    pair_metrics = (
        geometry.get("pair_metrics")
        or {}
    )

    start_width = pair_metrics.get(
        "start_width"
    )

    reference_price = pair_metrics.get(
        "reference_price"
    )

    if (
        start_width is None
        or reference_price is None
        or reference_price == 0
    ):
        return None

    potential_percent = (
        abs(float(start_width))
        / abs(float(reference_price))
        * 100.0
    )

    if pattern == "Falling Wedge":

        direction = "UP"
        signed_percent = potential_percent

    elif pattern == "Rising Wedge":

        direction = "DOWN"
        signed_percent = -potential_percent

    else:

        return None

    return {
        "percent":
            round(
                potential_percent,
                2
            ),

        "signed_percent":
            round(
                signed_percent,
                2
            ),

        "direction":
            direction,

        "method":
            "STRUCTURE_START_WIDTH"
    }
